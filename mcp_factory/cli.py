"""
Command-Line Interface (CLI) for MCPFactory.

Commands:
- `mcp-factory validate <config.json>`       : Validates a declarative JSON/YAML blueprint
- `mcp-factory inspect  <config.json>`       : Prints all registered backends, tools, resources, and prompts
- `mcp-factory run      <config.json>`       : Runs the MCP server in `http` (Cloud Run) or `stdio` mode
- `mcp-factory call     <config.json> <tool>`: Locally tests/executes a single tool from the CLI
- `mcp-factory import-openapi`               : Converts any OpenAPI 3.x / Swagger file into an MCP JSON blueprint
- `mcp-factory init     <output.json>`       : Scaffolds a starter MCP blueprint JSON file
- `mcp-factory deploy   <config.json>`       : Deploys the MCP server to Google Cloud Run via gcloud
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import subprocess
import sys
from pathlib import Path
from typing import Any

from mcp_factory.engine import MCPFactoryEngine
from mcp_factory.openapi_converter import convert_openapi_file
from mcp_factory.schema import load_blueprint
from mcp_factory.server import run_http_server, run_stdio_server


def cmd_validate(args: argparse.Namespace) -> int:
    try:
        blueprint = load_blueprint(args.config)
        print(f"✅ Blueprint '{args.config}' is valid!")
        print(f"   Server   : {blueprint.server.name} (v{blueprint.server.version})")
        print(f"   Backends : {len(blueprint.backends)} ({', '.join(blueprint.backends.keys())})")
        print(f"   Tools    : {len(blueprint.tools)}")
        print(f"   Resources: {len(blueprint.resources)}")
        print(f"   Prompts  : {len(blueprint.prompts)}")
        return 0
    except Exception as exc:
        print(f"❌ Validation failed for '{args.config}':\n   {exc}", file=sys.stderr)
        return 1


def cmd_inspect(args: argparse.Namespace) -> int:
    engine = MCPFactoryEngine.from_file(args.config)
    catalog = engine.get_catalog_summary()
    print(json.dumps(catalog, indent=2))
    return 0


def cmd_run(args: argparse.Namespace) -> int:
    config_path = args.config or os.environ.get("MCP_CONFIG_PATH", "configs/ecommerce_service.json")
    transport = (args.transport or os.environ.get("MCP_TRANSPORT", "http")).lower()
    host = args.host or os.environ.get("HOST", "0.0.0.0")
    port = int(args.port or os.environ.get("PORT", "8080"))

    engine = MCPFactoryEngine.from_file(config_path)

    if transport == "stdio":
        asyncio.run(run_stdio_server(engine))
    else:
        run_http_server(engine, host=host, port=port)
    return 0


def cmd_call(args: argparse.Namespace) -> int:
    engine = MCPFactoryEngine.from_file(args.config)
    try:
        tool_args = json.loads(args.args) if args.args else {}
    except json.JSONDecodeError as exc:
        print(f"❌ Invalid JSON passed to --args: {exc}", file=sys.stderr)
        return 1

    result = asyncio.run(engine.execute_tool(args.tool, tool_args))
    print(json.dumps(result, indent=2, default=str))
    return 0


def cmd_import_openapi(args: argparse.Namespace) -> int:
    blueprint = convert_openapi_file(
        input_path=args.input,
        output_path=args.output,
        backend_name=args.backend_name,
        base_url_override=args.base_url,
    )
    print(f"✅ Converted OpenAPI spec '{args.input}' -> '{args.output}'")
    print(f"   Generated {len(blueprint['tools'])} MCP tools for server '{blueprint['server']['name']}'.")
    return 0


def cmd_init(args: argparse.Namespace) -> int:
    out_path = Path(args.output)
    if out_path.exists() and not args.force:
        print(f"❌ File '{out_path}' already exists. Use --force to overwrite.", file=sys.stderr)
        return 1
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(STARTER_TEMPLATE, indent=2) + "\n", encoding="utf-8")
    print(f"✅ Created starter MCP blueprint at '{out_path}'.")
    print(f"   Validate it: mcp-factory validate {out_path}")
    print(f"   Run locally: mcp-factory run --config {out_path}")
    return 0


def cmd_deploy(args: argparse.Namespace) -> int:
    """Invokes deploy_cloud_run.sh or runs gcloud run deploy with the validated blueprint."""
    blueprint = load_blueprint(args.config)
    service_name = args.service_name or blueprint.server.name.lower().replace("_", "-")
    region = args.region or os.environ.get("GCP_REGION", "us-central1")
    project = args.project or os.environ.get("GCP_PROJECT_ID", "")

    script_path = Path(__file__).resolve().parent.parent / "deploy_cloud_run.sh"
    env = os.environ.copy()
    env["MCP_CONFIG_PATH"] = str(args.config)
    env["SERVICE_NAME"] = service_name
    env["REGION"] = region
    if project:
        env["PROJECT_ID"] = project
    if args.allow_unauthenticated:
        env["ALLOW_UNAUTHENTICATED"] = "true"
    else:
        env["ALLOW_UNAUTHENTICATED"] = "false"

    cmd = ["bash", str(script_path)]
    if args.dry_run:
        print("🔍 Dry-run mode: Cloud Run deployment configuration:")
        print(f"   Service Name : {service_name}")
        print(f"   Blueprint    : {args.config}")
        print(f"   Region       : {region}")
        print(f"   Project ID   : {project or '(current gcloud default)'}")
        print(f"   Command      : MCP_CONFIG_PATH={args.config} SERVICE_NAME={service_name} REGION={region} ./deploy_cloud_run.sh")
        return 0

    return subprocess.call(cmd, env=env)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="mcp-factory",
        description="Declarative JSON/YAML-driven MCP Server Framework & Cloud Run Deployer",
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    # validate
    p_val = subparsers.add_parser("validate", help="Validate an MCP JSON/YAML blueprint")
    p_val.add_argument("config", help="Path to blueprint JSON/YAML file")
    p_val.set_defaults(func=cmd_validate)

    # inspect
    p_ins = subparsers.add_parser("inspect", help="Inspect compiled tools, schemas, resources, and prompts")
    p_ins.add_argument("config", help="Path to blueprint JSON/YAML file")
    p_ins.set_defaults(func=cmd_inspect)

    # run
    p_run = subparsers.add_parser("run", help="Start the MCP server (HTTP/SSE for Cloud Run or stdio for Desktop)")
    p_run.add_argument("--config", "-c", default=None, help="Path to blueprint JSON/YAML file")
    p_run.add_argument(
        "--transport",
        "-t",
        choices=["http", "stdio"],
        default=None,
        help="Transport protocol: 'http' (Cloud Run SSE + JSON-RPC) or 'stdio' (Local Desktop)",
    )
    p_run.add_argument("--host", default=None, help="Bind host for HTTP mode (default: 0.0.0.0)")
    p_run.add_argument("--port", "-p", type=int, default=None, help="Bind port for HTTP mode (default: 8080)")
    p_run.set_defaults(func=cmd_run)

    # call
    p_call = subparsers.add_parser("call", help="Execute a tool directly from the CLI for rapid testing")
    p_call.add_argument("config", help="Path to blueprint JSON/YAML file")
    p_call.add_argument("tool", help="Name of the tool to execute")
    p_call.add_argument("--args", "-a", default="{}", help="JSON string of tool arguments (e.g. '{\"user_id\": 1}')")
    p_call.set_defaults(func=cmd_call)

    # import-openapi
    p_oa = subparsers.add_parser("import-openapi", help="Convert an OpenAPI 3.x / Swagger spec into an MCP blueprint")
    p_oa.add_argument("--input", "-i", required=True, help="Path to OpenAPI JSON or YAML file")
    p_oa.add_argument("--output", "-o", required=True, help="Output path for generated MCP blueprint JSON")
    p_oa.add_argument("--backend-name", default="default_api", help="Name of the generated backend block")
    p_oa.add_argument("--base-url", default=None, help="Override base URL for the backend")
    p_oa.set_defaults(func=cmd_import_openapi)

    # init
    p_init = subparsers.add_parser("init", help="Generate a starter MCP JSON blueprint")
    p_init.add_argument("output", nargs="?", default="configs/my_service.json", help="Output file path")
    p_init.add_argument("--force", "-f", action="store_true", help="Overwrite existing file")
    p_init.set_defaults(func=cmd_init)

    # deploy
    p_dep = subparsers.add_parser("deploy", help="Deploy the MCP server to Google Cloud Run")
    p_dep.add_argument("config", help="Path to blueprint JSON/YAML file to deploy")
    p_dep.add_argument("--service-name", "-s", default=None, help="Cloud Run service name")
    p_dep.add_argument("--project", "-p", default=None, help="Google Cloud Project ID")
    p_dep.add_argument("--region", "-r", default="us-central1", help="Google Cloud Run region")
    p_dep.add_argument(
        "--allow-unauthenticated",
        action="store_true",
        default=True,
        help="Allow public HTTP ingress (use MCP_SERVER_API_KEY for app-level auth)",
    )
    p_dep.add_argument("--dry-run", action="store_true", help="Print deployment configuration without running gcloud")
    p_dep.set_defaults(func=cmd_deploy)

    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
